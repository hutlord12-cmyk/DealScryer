function FS:GetLanguage()
    return "en"
end

function FS:SetLanguage()
    -- English-only build.
end

function FS:L(key, ...)
    local locale = self.LOCALES.en
    local value = locale[key] or key
    if select("#", ...) > 0 then
        local ok, formatted = pcall(string.format, value, ...)
        if ok then return formatted end
    end
    return value
end

function FS:LanguageName()
    return "English"
end

function FS:LocalizePhrase(text)
    if type(text) ~= "string" or text == "" then return text end
    local key = PHRASE_KEYS[text]
    if key then return self:L(key) end
    return text
end

function FS:LocalizeCommaList(text)
    if type(text) ~= "string" or text == "" then return text end
    local parts = {}
    for part in text:gmatch("[^,]+") do
        part = part:match("^%s*(.-)%s*$")
        parts[#parts + 1] = self:LocalizePhrase(part)
    end
    return table.concat(parts, ", ")
end

function FS:LocalizeReasonList(reasons)
    if type(reasons) ~= "table" then
        return self:L("TT_PRICE_UNRELIABLE")
    end
    local out = {}
    for _, reason in ipairs(reasons) do
        out[#out + 1] = self:LocalizePhrase(reason)
    end
    return table.concat(out, ", ")
end
